package ate_test

import (
	"context"
	"strings"
	"testing"

	"go.opentelemetry.io/otel"
	"go.opentelemetry.io/otel/propagation"
	"go.opentelemetry.io/otel/trace"
)

// The control-plane connection forwards the caller's W3C trace context, so
// ateapi's spans join the trace started by the SDK.
func TestControlPlaneCallsPropagateTraceContext(t *testing.T) {
	prev := otel.GetTextMapPropagator()
	otel.SetTextMapPropagator(propagation.TraceContext{})
	t.Cleanup(func() { otel.SetTextMapPropagator(prev) })

	f := newFixture(t)
	traceID, _ := trace.TraceIDFromHex("4bf92f3577b34da6a3ce929d0e0e4736")
	spanID, _ := trace.SpanIDFromHex("00f067aa0ba902b7")
	ctx := trace.ContextWithRemoteSpanContext(context.Background(), trace.NewSpanContext(trace.SpanContextConfig{
		TraceID:    traceID,
		SpanID:     spanID,
		TraceFlags: trace.FlagsSampled,
		Remote:     true,
	}))

	_, _ = f.client.Get(ctx, "", "missing") // NotFound is fine; we only need the call

	got := f.control.LastIncomingMetadata().Get("traceparent")
	if len(got) != 1 || !strings.Contains(got[0], traceID.String()) {
		t.Fatalf("traceparent = %q, want one header carrying trace id %s", got, traceID)
	}
}
