// Command metrics-docs renders docs/metrics.md, the reference of the
// Prometheus families ate-env-api serves, from telemetry.Definitions, the
// same definitions the server registers. Regenerate after changing a metric:
//
//	go run ./hack/metrics-docs > docs/metrics.md
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io"
	"os"
	"strconv"
	"strings"

	"github.com/agent-substrate/env/internal/telemetry"
)

func main() {
	output := flag.String("output", "", "file to write; empty writes to stdout")
	flag.Parse()

	var buf bytes.Buffer
	render(&buf)
	if *output == "" {
		if _, err := os.Stdout.Write(buf.Bytes()); err != nil {
			fmt.Fprintf(os.Stderr, "metrics-docs: %v\n", err)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(*output, buf.Bytes(), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "metrics-docs: %v\n", err)
		os.Exit(1)
	}
}

func render(w io.Writer) {
	fmt.Fprint(w, `<!-- Code generated by hack/metrics-docs from internal/telemetry. DO NOT EDIT. -->

# ate-env-api metrics

ate-env-api serves these Prometheus families at `+"`/metrics`"+` on the listener
`+"`--metrics-listen-addr`"+` names (default `+"`:9090`"+`; empty disables it). They live
on a private registry: no Go runtime or process collectors. Labels carry a
bounded vocabulary only; environment ids, actor ids, run ids, paths and image
references never appear in a label.

Histograms are in seconds with one bucket set:
`)
	fmt.Fprintf(w, "`%s`.\n\n", joinFloats(telemetry.SecondsBuckets))
	fmt.Fprintln(w, "| Name | Type | Labels | Description |")
	fmt.Fprintln(w, "|---|---|---|---|")
	for _, d := range telemetry.Definitions {
		labels := make([]string, len(d.Labels))
		for i, l := range d.Labels {
			labels[i] = "`" + l + "`"
		}
		fmt.Fprintf(w, "| `%s` | %s | %s | %s |\n", d.Name, d.Type, strings.Join(labels, ", "), strings.ReplaceAll(d.Help, "|", `\|`))
	}
	fmt.Fprintf(w, `
Clients may send `+"`%s`"+` (RFC 3339 with nanoseconds) as gRPC
metadata on `+"`CreateEnvironment`"+`; `+"`%s`"+` then starts at that time
instead of the server's receipt of the call.
`, telemetry.RequestedAtHeader, telemetry.MetricCreateToReadySeconds)
}

func joinFloats(fs []float64) string {
	parts := make([]string, len(fs))
	for i, f := range fs {
		parts[i] = strconv.FormatFloat(f, 'g', -1, 64)
	}
	return strings.Join(parts, ", ")
}
